export const CALLOUT_KINDS = ['info', 'note', 'tip', 'warning', 'danger', 'success'] as const;
export type CalloutKind = (typeof CALLOUT_KINDS)[number];

function isCalloutKind(value: string): value is CalloutKind {
  return (CALLOUT_KINDS as readonly string[]).includes(value);
}

const CALLOUT_LABEL: Record<CalloutKind, string> = {
  info: 'Info',
  note: 'Note',
  tip: 'Tip',
  warning: 'Warning',
  danger: 'Danger',
  success: 'Success',
};

// ---------------------------------------------------------------------------
// Tokenizer
//
// Turns raw source into a flat array of top-level Block tokens. Container
// blocks (callouts, collapse, tabs, box, columns) hold their inner raw text
// unparsed — it's recursively run back through render() at render time,
// which is what allows arrow syntax / nested containers to work inside a
// container without the outer scanner needing to understand every possible
// nested construct up front.
// ---------------------------------------------------------------------------

type Block =
  | { type: 'codeblock'; lang: string; code: string }
  | { type: 'heading'; level: 1 | 2 | 3; hashStyle: boolean; text: string }
  | { type: 'hr' }
  | { type: 'table'; header: string[]; align: string[]; rows: string[][] }
  | { type: 'blockquote'; lines: string[] }
  | { type: 'list'; kind: 'ul' | 'ol'; items: string[] }
  | { type: 'box'; color: BoxColor; title: string; body: string }
  | { type: 'columns'; left: string; right: string }
  | { type: 'callout'; kind: CalloutKind; body: string }
  | { type: 'collapse'; label: string; body: string }
  | { type: 'tabs'; tabs: { title: string; body: string }[] }
  | { type: 'paragraph'; text: string };

const SECTION_OPEN = /^<-(Section|SubSection|SubSubSection)-(.*)->\s*$/;
const TAB_OPEN = /^<-Tab-(.*)->\s*$/;

/**
 * Find the matching ":::" close for a container that was opened at `start`
 * (the line AFTER the opening fence). Nested ":::..." opens increase depth;
 * bare ":::" closes decrease it. Code fences inside the container are
 * skipped over so a "```" block containing literal ":::" text can never
 * accidentally close (or nest) a container.
 */
function findContainerClose(lines: string[], start: number): number {
  let depth = 1;
  let i = start;
  let inCodeFence = false;
  while (i < lines.length) {
    const trimmed = lines[i].trim();
    if (/^```/.test(trimmed)) {
      inCodeFence = !inCodeFence;
      i++;
      continue;
    }
    if (!inCodeFence) {
      if (trimmed === ':::') {
        depth--;
        if (depth === 0) return i;
      } else if (/^:::\S/.test(trimmed)) {
        depth++;
      }
    }
    i++;
  }
  return lines.length; // unterminated — fail gracefully, treat rest as body
}

function tokenize(source: string): Block[] {
  const lines = source.split('\n');
  const blocks: Block[] = [];
  let i = 0;
  let listBuffer: { kind: 'ul' | 'ol'; items: string[] } | null = null;

  function flushList() {
    if (listBuffer) {
      blocks.push({ type: 'list', kind: listBuffer.kind, items: listBuffer.items });
      listBuffer = null;
    }
  }

  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();

    // Fenced code block — protected verbatim, never scanned for structure.
    if (/^```/.test(trimmed)) {
      flushList();
      const lang = trimmed.slice(3).trim();
      const codeLines: string[] = [];
      i++;
      while (i < lines.length && !/^```/.test(lines[i].trim())) {
        codeLines.push(lines[i]);
        i++;
      }
      i++; // skip closing fence
      blocks.push({ type: 'codeblock', lang, code: codeLines.join('\n') });
      continue;
    }

    // ":::" containers — box, columns, collapse, tabs, and semantic callouts.
    const boxOpen = trimmed.match(/^:::box(?:\s+(\S+))?(?:\s+"([^"]*)")?\s*$/);
    const columnsOpen = /^:::columns\s*$/.test(trimmed);
    const collapseOpen = trimmed.match(/^:::collapse(?:\s+"([^"]*)")?\s*$/);
    const tabsOpen = /^:::tabs\s*$/.test(trimmed);
    const calloutOpen = trimmed.match(/^:::([a-zA-Z]+)\s*$/);

    if (boxOpen) {
      flushList();
      const colorArg = (boxOpen[1] || '').toLowerCase();
      const color: BoxColor = isBoxColor(colorArg) ? colorArg : 'violet';
      const title = boxOpen[2] || '';
      const closeAt = findContainerClose(lines, i + 1);
      const body = lines.slice(i + 1, closeAt).join('\n');
      blocks.push({ type: 'box', color, title, body });
      i = closeAt + 1;
      continue;
    }

    if (columnsOpen) {
      flushList();
      const closeAt = findContainerClose(lines, i + 1);
      const bodyLines = lines.slice(i + 1, closeAt);
      const sepIdx = bodyLines.findIndex((l) => l.trim() === '---');
      const left = sepIdx === -1 ? bodyLines.join('\n') : bodyLines.slice(0, sepIdx).join('\n');
      const right = sepIdx === -1 ? '' : bodyLines.slice(sepIdx + 1).join('\n');
      blocks.push({ type: 'columns', left, right });
      i = closeAt + 1;
      continue;
    }

    if (collapseOpen) {
      flushList();
      const label = collapseOpen[1] || 'Click to expand';
      const closeAt = findContainerClose(lines, i + 1);
      const body = lines.slice(i + 1, closeAt).join('\n');
      blocks.push({ type: 'collapse', label, body });
      i = closeAt + 1;
      continue;
    }

    if (tabsOpen) {
      flushList();
      const closeAt = findContainerClose(lines, i + 1);
      const bodyLines = lines.slice(i + 1, closeAt);
      const tabs: { title: string; body: string }[] = [];
      let j = 0;
      // Skip any stray content before the first <-Tab-...-> marker (ignored,
      // fails gracefully rather than crashing on malformed input).
      while (j < bodyLines.length && !TAB_OPEN.test(bodyLines[j].trim())) j++;
      while (j < bodyLines.length) {
        const m = bodyLines[j].trim().match(TAB_OPEN);
        if (!m) {
          j++;
          continue;
        }
        const title = m[1].trim();
        j++;
        const contentLines: string[] = [];
        while (j < bodyLines.length && !TAB_OPEN.test(bodyLines[j].trim())) {
          contentLines.push(bodyLines[j]);
          j++;
        }
        tabs.push({ title, body: contentLines.join('\n') });
      }
      blocks.push({ type: 'tabs', tabs });
      i = closeAt + 1;
      continue;
    }

    if (calloutOpen && isCalloutKind(calloutOpen[1].toLowerCase())) {
      flushList();
      const kind = calloutOpen[1].toLowerCase() as CalloutKind;
      const closeAt = findContainerClose(lines, i + 1);
      const body = lines.slice(i + 1, closeAt).join('\n');
      blocks.push({ type: 'callout', kind, body });
      i = closeAt + 1;
      continue;
    }

    // DOCLIX structural heading: <-Section-Title-> / <-SubSection-Title-> / <-SubSubSection-Title->
    const sectionMatch = trimmed.match(SECTION_OPEN);
    if (sectionMatch) {
      flushList();
      const level = sectionMatch[1] === 'Section' ? 1 : sectionMatch[1] === 'SubSection' ? 2 : 3;
      blocks.push({ type: 'heading', level: level as 1 | 2 | 3, hashStyle: false, text: sectionMatch[2] });
      i++;
      continue;
    }

    // Tables: header row, separator row (---|---), then body rows.
    if (trimmed.includes('|') && i + 1 < lines.length && isTableSeparatorRow(lines[i + 1])) {
      flushList();
      const header = splitTableRow(line);
      const align = splitTableRow(lines[i + 1]).map((c) => {
        const left = c.startsWith(':');
        const right = c.endsWith(':');
        if (left && right) return 'center';
        if (right) return 'right';
        if (left) return 'left';
        return '';
      });
      i += 2;
      const rows: string[][] = [];
      while (i < lines.length && lines[i].trim().includes('|') && lines[i].trim() !== '') {
        rows.push(splitTableRow(lines[i]));
        i++;
      }
      blocks.push({ type: 'table', header, align, rows });
      continue;
    }

    // Horizontal rule
    if (/^-{3,}$/.test(trimmed)) {
      flushList();
      blocks.push({ type: 'hr' });
      i++;
      continue;
    }

    // "#"-style headings (kept for backward compatibility)
    const h3 = line.match(/^###\s+(.*)/);
    const h2 = line.match(/^##\s+(.*)/);
    const h1 = line.match(/^#\s+(.*)/);
    if (h3) {
      flushList();
      blocks.push({ type: 'heading', level: 3, hashStyle: true, text: h3[1] });
      i++;
      continue;
    }
    if (h2) {
      flushList();
      blocks.push({ type: 'heading', level: 2, hashStyle: true, text: h2[1] });
      i++;
      continue;
    }
    if (h1) {
      flushList();
      blocks.push({ type: 'heading', level: 1, hashStyle: true, text: h1[1] });
      i++;
      continue;
    }

    // Blockquote
    if (/^>\s?/.test(line)) {
      flushList();
      const quoteLines = [line.replace(/^>\s?/, '')];
      i++;
      while (i < lines.length && /^>\s?/.test(lines[i])) {
        quoteLines.push(lines[i].replace(/^>\s?/, ''));
        i++;
      }
      blocks.push({ type: 'blockquote', lines: quoteLines });
      continue;
    }

    // Numbered list
    const ol = line.match(/^\d+\.\s+(.*)/);
    if (ol) {
      if (!listBuffer || listBuffer.kind !== 'ol') {
        flushList();
        listBuffer = { kind: 'ol', items: [] };
      }
      listBuffer.items.push(ol[1]);
      i++;
      continue;
    }

    // Bullet list
    const ul = line.match(/^[-*]\s+(.*)/);
    if (ul) {
      if (!listBuffer || listBuffer.kind !== 'ul') {
        flushList();
        listBuffer = { kind: 'ul', items: [] };
      }
      listBuffer.items.push(ul[1]);
      i++;
      continue;
    }

    // Blank line
    if (trimmed === '') {
      flushList();
      i++;
      continue;
    }

    // Paragraph
    flushList();
    blocks.push({ type: 'paragraph', text: line });
    i++;
  }

  flushList();
  return blocks;
}

// ---------------------------------------------------------------------------
// Renderer — walks tokens to HTML, sharing a single heading-slug map across
// the whole render (threaded through recursive calls) so anchors stay
// unique across nested containers/tabs too.
// ---------------------------------------------------------------------------

let tabGroupCounter = 0;

// A single "cell" of inline content (paragraph line, table cell, list item,
// heading label, collapse/tab label) goes through the escape-then-inline
// pipeline.
function renderCell(raw: string, opts: RenderOptions): string {
  const escaped = escapeHtml(protectEscapedChars(raw));
  return restoreEscapedChars(renderInline(escaped, opts));
}

function renderBlocks(blocks: Block[], opts: RenderOptions, slugSeen: Map<string, number>): string {
  const html: string[] = [];

  function slugFor(text: string): string {
    return slugify(text, slugSeen);
  }

  for (const block of blocks) {
    switch (block.type) {
      case 'codeblock': {
        const code = escapeHtml(block.code);
        html.push(
          `<div class="doclix-codeblock"><button type="button" class="doclix-copy-btn" data-doclix-copy aria-label="Copy code"><span class="doclix-copy-label">Copy</span></button><pre><code${
            block.lang ? ` class="language-${attr(block.lang)}"` : ''
          }>${code}</code></pre></div>`
        );
        break;
      }
      case 'heading': {
        const id = slugFor(block.text);
        const tag = `h${block.level}`;
        const cls = block.hashStyle ? '' : ` class="doclix-heading doclix-heading-${block.level}"`;
        html.push(`<${tag} id="${attr(id)}"${cls}>${renderCell(block.text.trim(), opts)}</${tag}>`);
        break;
      }
      case 'hr':
        html.push('<hr />');
        break;
      case 'table': {
        const alignStyle = (idx: number) => (block.align[idx] ? ` style="text-align:${block.align[idx]}"` : '');
        const thead = `<thead><tr>${block.header
          .map((c, idx) => `<th${alignStyle(idx)}>${renderCell(c, opts)}</th>`)
          .join('')}</tr></thead>`;
        const tbody = `<tbody>${block.rows
          .map(
            (row) => `<tr>${row.map((c, idx) => `<td${alignStyle(idx)}>${renderCell(c, opts)}</td>`).join('')}</tr>`
          )
          .join('')}</tbody>`;
        html.push(`<div class="doclix-table-wrap"><table>${thead}${tbody}</table></div>`);
        break;
      }
      case 'blockquote':
        html.push(`<blockquote>${block.lines.map((l) => renderCell(l, opts)).join('<br/>')}</blockquote>`);
        break;
      case 'list':
        html.push(
          `<${block.kind}>${block.items.map((item) => `<li>${renderCell(item, opts)}</li>`).join('')}</${block.kind}>`
        );
        break;
      case 'box': {
        const hex = BOX_COLOR_HEX[block.color];
        const titleHtml = block.title ? `<div class="doclix-box-title">${renderCell(block.title, opts)}</div>` : '';
        html.push(
          `<div class="doclix-box doclix-box-${block.color}" style="--doclix-box-color:${hex}">${titleHtml}${render(
            block.body,
            opts,
            slugSeen
          )}</div>`
        );
        break;
      }
      case 'columns':
        html.push(
          `<div class="doclix-columns"><div class="doclix-column">${render(
            block.left,
            opts,
            slugSeen
          )}</div><div class="doclix-column">${render(block.right, opts, slugSeen)}</div></div>`
        );
        break;
      case 'callout': {
        const label = CALLOUT_LABEL[block.kind];
        html.push(
          `<div class="doclix-callout doclix-callout-${block.kind}" role="note"><div class="doclix-callout-label">${label}</div><div class="doclix-callout-body">${render(
            block.body,
            opts,
            slugSeen
          )}</div></div>`
        );
        break;
      }
      case 'collapse': {
        const label = renderCell(block.label, opts);
        html.push(
          `<details class="doclix-collapse"><summary class="doclix-collapse-summary">${label}</summary><div class="doclix-collapse-body">${render(
            block.body,
            opts,
            slugSeen
          )}</div></details>`
        );
        break;
      }
      case 'tabs': {
        if (block.tabs.length === 0) break;
        const groupId = `doclix-tabgroup-${++tabGroupCounter}`;
        const tabButtons = block.tabs
          .map(
            (t, idx) =>
              `<button type="button" class="doclix-tab-btn${
                idx === 0 ? ' doclix-tab-btn-active' : ''
              }" data-doclix-tab-btn data-tab-index="${idx}">${renderCell(t.title, opts)}</button>`
          )
          .join('');
        const panels = block.tabs
          .map(
            (t, idx) =>
              `<div class="doclix-tab-panel${
                idx === 0 ? ' doclix-tab-panel-active' : ''
              }" data-doclix-tab-panel data-tab-index="${idx}">${render(t.body, opts, slugSeen)}</div>`
          )
          .join('');
        html.push(
          `<div class="doclix-tabs" id="${groupId}" data-doclix-tabs><div class="doclix-tab-list" role="tablist">${tabButtons}</div><div class="doclix-tab-panels">${panels}</div></div>`
        );
        break;
      }
      case 'paragraph':
        html.push(`<p>${renderCell(block.text, opts)}</p>`);
        break;
    }
  }

  return html.join('\n');
}

/**
 * Render a chunk of DOCLIX source (top-level document, or the body of a
 * container/tab/collapse) to HTML, sharing the heading-slug map so ids stay
 * unique across the whole document even when headings appear inside
 * containers.
 */
function render(source: string, opts: RenderOptions, slugSeen: Map<string, number>): string {
  const blocks = tokenize(source);
  return renderBlocks(blocks, opts, slugSeen);
}

export function renderMarkdown(source: string, projectSlugOrOpts?: string | RenderOptions): string {
  const opts: RenderOptions =
    typeof projectSlugOrOpts === 'string' ? { projectSlug: projectSlugOrOpts } : projectSlugOrOpts || {};
  const slugSeen = new Map<string, number>();
  return render(source, opts, slugSeen);
}
