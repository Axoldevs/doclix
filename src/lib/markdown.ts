/**
 * DOCLIX Markup Language renderer.
 *
 * Backward-compatible superset of the original Discord-style Markdown
 * renderer. Supports everything it did before (bold, italic, underline,
 * strikethrough, inline code, code blocks, # ## ### headings, lists,
 * blockquotes, links, images, tables, hr, ":::box", ":::columns") plus the
 * DOCLIX-native syntax:
 *
 *   <-Section-Title->            structural heading, level 1
 *   <-SubSection-Title->         structural heading, level 2
 *   <-SubSubSection-Title->      structural heading, level 3
 *   :::info / :::note / :::tip / :::warning / :::danger / :::success
 *                                 semantic callout containers (nestable)
 *   :::collapse "Label"           collapsible section
 *   :::tabs ... <-Tab-Name-> ... interactive tab group
 *   [[Page]] / [[Page|Text]]      internal DOCLIX document link
 *   [[Page#anchor]]               internal link with anchor
 *
 * Design: this is a two-pass, block-oriented parser, not a bag of regexes.
 * Pass 1 tokenizes the raw source into a flat list of block Tokens with a
 * simple bracket-matching scanner that understands nesting (containers can
 * contain containers, arrow elements, tabs, code fences, etc). Pass 2 walks
 * the token tree and renders each token to HTML. Code fences are located
 * and protected in the same tokenizing pass so nothing inside them is ever
 * misread as structural syntax.
 *
 * HTML safety: all raw text is escaped before any structural markers are
 * interpreted, and every value that ends up as an HTML attribute (href,
 * id, class, style) is generated by this module rather than passed through
 * verbatim, so user-authored text cannot break out of an attribute or
 * inject a tag/script.
 */

export interface HeadingItem {
  level: 1 | 2 | 3;
  text: string;
  id: string;
}

// Characters that can be backslash-escaped per standard Markdown (plus the
// DOCLIX-native "<" and ":" so "<-Section-...->" and ":::" fences can be
// escaped to appear literally, e.g. in documentation about DOCLIX itself).
const ESCAPABLE_CHARS = '\\`*_{}[]()#+-.!>~|<:';

// ---------------------------------------------------------------------------
// Shared small utilities
// ---------------------------------------------------------------------------

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Safe for use inside an HTML attribute value (already-escaped text). */
function attr(str: string): string {
  return escapeHtml(str);
}

function stripEscapes(text: string): string {
  let out = '';
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];
    if (ch === '\\' && next && ESCAPABLE_CHARS.includes(next)) {
      out += next;
      i++;
    } else {
      out += ch;
    }
  }
  return out;
}

/**
 * Replace backslash-escaped markdown-significant characters (e.g. "\*",
 * "\_", "\#", "\<", "\:") with a placeholder token holding the literal
 * character, so later block/inline parsing doesn't treat it as syntax.
 * Tokens are resolved back to plain text at the very end of rendering.
 */
function protectEscapedChars(text: string): string {
  let out = '';
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];
    if (ch === '\\' && next && ESCAPABLE_CHARS.includes(next)) {
      out += `\u0000ESC${next.charCodeAt(0)}\u0000`;
      i++;
    } else {
      out += ch;
    }
  }
  return out;
}

function restoreEscapedChars(html: string): string {
  return html.replace(/\u0000ESC(\d+)\u0000/g, (_m, code) => {
    const ch = String.fromCharCode(Number(code));
    return escapeHtml(ch);
  });
}

// A single seen-slug map is threaded through a whole render so that
// duplicate headings across the *entire* document (not just one nesting
// level) get collision-safe ids: "installation", "installation-2", ...
function slugify(text: string, seen: Map<string, number>): string {
  const base = text
    .toLowerCase()
    .trim()
    .replace(/&[a-z]+;/g, '')
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  const safeBase = base || 'section';
  const count = seen.get(safeBase) ?? 0;
  seen.set(safeBase, count + 1);
  return count === 0 ? safeBase : `${safeBase}-${count}`;
}

// ---------------------------------------------------------------------------
// extractHeadings — used by the ToC panel. Understands both "#"-style and
// DOCLIX-native "<-Section-...->" structural headings.
// ---------------------------------------------------------------------------

export function extractHeadings(source: string): HeadingItem[] {
  const lines = source.split('\n');
  const seen = new Map<string, number>();
  const headings: HeadingItem[] = [];
  let inFence = false; // ``` code fence
  let depth = 0; // ::: nesting depth — headings inside containers still count

  for (const line of lines) {
    const trimmed = line.trim();

    if (/^```/.test(trimmed)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;

    if (/^:::/.test(trimmed)) {
      if (trimmed === ':::') {
        depth = Math.max(0, depth - 1);
      } else {
        depth++;
      }
      continue;
    }

    const sectionMatch = trimmed.match(/^<-(Section|SubSection|SubSubSection)-(.*)->\s*$/);
    if (sectionMatch) {
      const level = sectionMatch[1] === 'Section' ? 1 : sectionMatch[1] === 'SubSection' ? 2 : 3;
      const text = stripEscapes(sectionMatch[2].trim());
      headings.push({ level: level as 1 | 2 | 3, text, id: slugify(sectionMatch[2], seen) });
      continue;
    }

    const h3 = line.match(/^###\s+(.*)/);
    const h2 = line.match(/^##\s+(.*)/);
    const h1 = line.match(/^#\s+(.*)/);
    if (h3) headings.push({ level: 3, text: stripEscapes(h3[1].trim()), id: slugify(h3[1], seen) });
    else if (h2) headings.push({ level: 2, text: stripEscapes(h2[1].trim()), id: slugify(h2[1], seen) });
    else if (h1) headings.push({ level: 1, text: stripEscapes(h1[1].trim()), id: slugify(h1[1], seen) });
  }

  return headings;
}

// ---------------------------------------------------------------------------
// Inline rendering (bold/italic/links/images/inline code/internal links)
// ---------------------------------------------------------------------------

export interface RenderOptions {
  /**
   * Slug of the current project, used to resolve internal DOCLIX links
   * ("[[Page]]") to a real href of the form "/docs/{projectSlug}/{page}".
   * If omitted, internal links render as "#" placeholders (still safe,
   * just non-navigable) so the renderer degrades gracefully wherever a
   * project context isn't available (e.g. isolated previews).
   */
  projectSlug?: string;
}

const DANGEROUS_URL = /^\s*(javascript|data|vbscript):/i;

function sanitizeUrl(url: string): string | null {
  const trimmed = url.trim();
  if (DANGEROUS_URL.test(trimmed)) return null;
  return trimmed;
}

function slugifyLinkTarget(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\w\s/-]/g, '')
    .replace(/\s+/g, '-');
}

function renderInline(text: string, opts: RenderOptions = {}): string {
  let out = text;

  // Inline code (protect content from further inline processing)
  const codeTokens: string[] = [];
  out = out.replace(/`([^`]+)`/g, (_m, code) => {
    codeTokens.push(code);
    return `\u0000CODE${codeTokens.length - 1}\u0000`;
  });

  // Internal DOCLIX links: [[Page]], [[Page|Text]], [[Page#anchor]],
  // [[Page#anchor|Text]]. Handled before external links/images since the
  // double-bracket syntax differs and must not be swallowed by them.
  out = out.replace(
    /\[\[([^\]|#]+)(?:#([^\]|]+))?(?:\|([^\]]+))?\]\]/g,
    (_m, page: string, anchor: string | undefined, label: string | undefined) => {
      const pageName = page.trim();
      const anchorName = (anchor ?? '').trim();
      const linkLabel = (label ?? pageName).trim();
      const targetSlug = slugifyLinkTarget(pageName);
      const base = opts.projectSlug
        ? `/docs/${encodeURIComponent(opts.projectSlug)}/${encodeURIComponent(targetSlug)}`
        : '#';
      const href = anchorName ? `${base}#${slugifyLinkTarget(anchorName)}` : base;
      return `<a href="${attr(href)}" class="doclix-internal-link" data-doclix-internal="1">${renderInline(
        linkLabel,
        opts
      )}</a>`;
    }
  );

  // Images ![alt](url) — must be handled before links, since the link
  // pattern would otherwise match the "[alt](url)" part and leave a stray "!".
  out = out.replace(/!\[([^\]]*)\]\((\S+?)\)/g, (_m, alt, url) => {
    const safe = sanitizeUrl(url);
    if (!safe) return '';
    return `<img src="${attr(safe)}" alt="${attr(alt)}" loading="lazy" />`;
  });

  // Links [text](url)
  out = out.replace(/\[([^\]]+)\]\((\S+?)\)/g, (_m, label, url) => {
    const safe = sanitizeUrl(url);
    if (!safe) return label;
    return `<a href="${attr(safe)}" target="_blank" rel="noopener noreferrer">${label}</a>`;
  });

  // Bold **text**
  out = out.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  // Underline __text__
  out = out.replace(/__([^_]+)__/g, '<u>$1</u>');
  // Strikethrough ~~text~~
  out = out.replace(/~~([^~]+)~~/g, '<del>$1</del>');
  // Italic *text* (single asterisks, after bold has been consumed)
  out = out.replace(/\*([^*]+)\*/g, '<em>$1</em>');

  // Restore code tokens
  out = out.replace(/\u0000CODE(\d+)\u0000/g, (_m, i) => {
    return `<code>${escapeHtml(codeTokens[Number(i)])}</code>`;
  });

  return out;
}

// ---------------------------------------------------------------------------
// Table helpers (unchanged behavior, kept for existing callers / tableOps)
// ---------------------------------------------------------------------------

export function isTableSeparatorRow(line: string): boolean {
  const trimmed = line.trim();
  if (!trimmed.includes('-') || !trimmed.includes('|')) return false;
  const cells = trimmed.replace(/^\|/, '').replace(/\|$/, '').split('|');
  return cells.length > 0 && cells.every((c) => /^\s*:?-+:?\s*$/.test(c));
}

export function splitTableRow(line: string): string[] {
  let trimmed = line.trim();
  if (trimmed.startsWith('|')) trimmed = trimmed.slice(1);
  if (trimmed.endsWith('|')) trimmed = trimmed.slice(0, -1);
  return trimmed.split('|').map((c) => c.trim());
}

